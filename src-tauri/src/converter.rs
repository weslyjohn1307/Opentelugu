#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ConversionResult {
    pub pua_text: String,
    pub ansi_text: String,
    pub original: String,
}

#[inline]
fn is_telugu_char(c: char) -> bool {
    let cp = c as u32;
    (3072..=3199).contains(&cp)
}

fn ks_splice(chars: &mut Vec<char>, src_idx: usize, dest_idx: usize) {
    if src_idx < chars.len() && dest_idx < chars.len() {
        let item = chars.remove(src_idx);
        chars.insert(dest_idx, item);
    }
}

/// Reorders ra-vatthu ( = \u{f0e7} and  = \u{f081}) before base consonants
pub fn reorder_ro(text: &str) -> String {
    let mut chars: Vec<char> = text.chars().collect();
    let mut consonant_idx: i32 = -1;
    let mut i = 0;

    while i < chars.len() {
        let ch = chars[i];
        let ch_str = ch.to_string();

        if ch == '\u{f0e7}' || ch == '\u{f081}' {
            if consonant_idx >= 0 && (consonant_idx as usize) < chars.len() {
                ks_splice(&mut chars, i, consonant_idx as usize);
            }
        } else if SO_CONSONANTS.contains(&ch_str.as_str()) {
            consonant_idx = i as i32;
        }
        i += 1;
    }

    chars.into_iter().collect()
}

/// Reorders vowel signs before base consonants if preceding char is not Telugu
pub fn reorder_oo(text: &str) -> String {
    let mut chars: Vec<char> = text.chars().collect();
    let mut telugu_idx: i32 = -1;
    let mut i = 0;

    while i < chars.len() {
        let ch = chars[i];
        let ch_str = ch.to_string();

        if NO_VOWEL_SIGNS.contains(&ch_str.as_str()) {
            let prev_is_telugu = if i > 0 { is_telugu_char(chars[i - 1]) } else { false };
            if !prev_is_telugu && telugu_idx >= 0 {
                let dest = (telugu_idx + 1) as usize;
                if dest < chars.len() {
                    ks_splice(&mut chars, i, dest);
                }
            }
        } else if is_telugu_char(ch) {
            telugu_idx = i as i32;
        }
        i += 1;
    }

    chars.into_iter().collect()
}

/// Converts Telugu Unicode text to Script PUA character string
pub fn telugu_to_script_pua(input: &str) -> String {
    let mut t = input.to_string();

    // 1. Ksh substitution
    t = t.replace("క్ష", "ౡ");

    // 2. Special replacements
    for &(src, dst) in SPECIAL_MAP {
        t = t.replace(src, dst);
    }

    // 3. Normalize newlines
    t = t.replace('\n', "\r\n");

    // 4. Tri-consonant ra-vatthu conjuncts
    for &s in IO_LIST {
        let chars: Vec<char> = s.chars().collect();
        if chars.len() >= 2 {
            let replacement = format!("{}{}{}", chars[0], chars[1], AO_MARKER);
            t = t.replace(s, &replacement);
        }
    }

    // 5. Subscript vatthulu replacements
    for &(src, dst) in VOTHULU_MAP {
        t = t.replace(src, dst);
    }

    // 6. Ro reordering
    t = reorder_ro(&t);

    // 7. Restore Ksh
    t = t.replace("ౡ", "క్ష");

    // 8. Oo vowel sign reordering
    t = reorder_oo(&t);

    // 9. Non-vothulu base glyph replacements
    for &(src, dst) in NON_VOTHULU_MAP {
        t = t.replace(src, dst);
    }

    // 10. Clean up invisible format characters (ZWNJ and ZWJ)
    t = t.replace('\u{200c}', "");
    t = t.replace('\u{200d}', "");

    t
}

/// Converts Script PUA characters to 8-bit ANSI bytes (Windows-1252)
pub fn pua_to_ansi_bytes(pua: &str) -> Vec<u8> {
    let mut bytes = Vec::with_capacity(pua.len());
    for c in pua.chars() {
        let cp = c as u32;
        if (0xF000..=0xF0FF).contains(&cp) {
            bytes.push((cp - 0xF000) as u8);
        } else if cp <= 0x7F {
            bytes.push(cp as u8);
        } else {
            match cp {
                0x20AC => bytes.push(0x80),
                0x201A => bytes.push(0x82),
                0x0192 => bytes.push(0x83),
                0x201E => bytes.push(0x84),
                0x2026 => bytes.push(0x85),
                0x2020 => bytes.push(0x86),
                0x2021 => bytes.push(0x87),
                0x02C6 => bytes.push(0x88),
                0x2030 => bytes.push(0x89),
                0x0160 => bytes.push(0x8A),
                0x2039 => bytes.push(0x8B),
                0x0152 => bytes.push(0x8C),
                0x017D => bytes.push(0x8E),
                0x2018 => bytes.push(0x91),
                0x2019 => bytes.push(0x92),
                0x201C => bytes.push(0x93),
                0x201D => bytes.push(0x94),
                0x2022 => bytes.push(0x95),
                0x2013 => bytes.push(0x96),
                0x2014 => bytes.push(0x97),
                0x02DC => bytes.push(0x98),
                0x2122 => bytes.push(0x99),
                0x0161 => bytes.push(0x9A),
                0x203A => bytes.push(0x9B),
                0x0153 => bytes.push(0x9C),
                0x017E => bytes.push(0x9E),
                0x0178 => bytes.push(0x9F),
                0xA0..=0xFF => bytes.push(cp as u8),
                _ => bytes.push(b'?'),
            }
        }
    }
    bytes
}

/// Converts Script PUA characters to a Windows-1252 string representation
pub fn pua_to_ansi_string(pua: &str) -> String {
    let bytes = pua_to_ansi_bytes(pua);
    bytes.iter().map(|&b| b as char).collect()
}

/// Full conversion pipeline
pub fn convert(text: &str) -> ConversionResult {
    let pua = telugu_to_script_pua(text);
    let ansi = pua_to_ansi_string(&pua);
    ConversionResult {
        pua_text: pua,
        ansi_text: ansi,
        original: text.to_string(),
    }
}

